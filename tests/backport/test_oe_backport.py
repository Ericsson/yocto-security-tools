def test_existing_bbappend_is_preserved_and_extended(monkeypatch, tmp_path):
    cve = "CVE-2025-1234"
    repo_dir = _cached_repo(tmp_path, cve)
    layer = tmp_path / "layer"
    append = layer / "recipes-connectivity/avahi/avahi_0.8.bbappend"
    append.parent.mkdir(parents=True)
    append.write_text('SUMMARY = "Existing append"\n')
    _set_repo_urls(monkeypatch)

    results = oe_backport.prepare_backports(
        _cache(cve, f'merged: "2026-02-27 4da15f7fad8d avahi: patch {cve} by Test"'),
        _metadata(cve), repo_dir, layer)

    content = append.read_text()
    assert results[0]["status"] == "prepared"
    assert content.startswith('SUMMARY = "Existing append"\n')
    assert "Generated by cve-oe-backport" in content
    assert 'file://CVE-2025-1234.patch' in content
